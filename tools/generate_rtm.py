#!/usr/bin/env python3
"""Generate docs/14-traceability/requirement-traceability-matrix.md from requirement tables.

Reads every requirement definition row (see DOCUMENTATION_STANDARD.md section 2) and
every test case row (HAK-TC-nnn, last column 'Verifies'). Deterministic output.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import hakuren_audit as A  # noqa: E402

defs = A.definitions()
reqs = {i: l[0] for i, l in defs.items() if i.split("-")[1] in A.REQ_PREFIXES}
tc = {}
for i, locs in defs.items():
    if i.startswith("HAK-TC-"):
        for m in A.ID_RE.finditer(locs[0][1][-1]):
            tc.setdefault(m.group(0), []).append(i)

def esc(s):
    return s.replace("|", "/")

rows = []
for i in sorted(reqs):
    f, c = reqs[i]
    if len(c) < 10:
        continue
    tests = ", ".join(sorted(tc.get(i, []))) or "NONE"
    rows.append(f"| {i} | {esc(c[1])} | {i.split('-')[1]} | {c[3]} | [{Path(f).name}]({'../' + '/'.join(Path(f).parts[1:])}) | {esc(c[7])} | {esc(c[8])} | {tests} | {c[9]} |")

cats = {}
for i in reqs:
    cats[i.split("-")[1]] = cats.get(i.split("-")[1], 0) + 1
no_test = sum(1 for i in reqs if i not in tc)
out = f"""# Requirement Traceability Matrix

| Field | Value |
|---|---|
| Doc ID | HAK-DOC-RTM |
| Status | Draft |

Generated by `tools/generate_rtm.py`; do not edit by hand. Total requirements: {len(reqs)}. By category: {dict(sorted(cats.items()))}. Requirements with no verifying test case: {no_test}.

| ID | Name | Category | Priority | Specification | Verification | Acceptance | Test cases | Status |
|---|---|---|---|---|---|---|---|---|
""" + "\n".join(rows) + "\n"
dest = A.DOCS / "14-traceability" / "requirement-traceability-matrix.md"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text(out, encoding="utf-8")
print(f"wrote {dest} ({len(rows)} rows)")
